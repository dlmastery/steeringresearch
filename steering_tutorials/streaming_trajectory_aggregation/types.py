# --- data models -------------------------------------------------------------
@dataclass(frozen=True)
class Step:
    """One step of one agent trajectory.

    ``index`` is the 0-based position within its trajectory. ``text`` is the rendered
    step (the unit we embed). The remaining fields come from the judge log when the
    corpus has one and are ``None`` otherwise -- a corpus with only trajectory-level
    labels still yields valid Steps with every optional field ``None``.
    """

    index: int
    text: str
    # --- per-step judge tracks (SHADE monitor-labels; None elsewhere) ---
    on_path: bool | None = None
    severity_if_confirmed: float | None = None
    irreversibility_imminent: bool | None = None
    # the CAUSAL reference monitor -- a baseline to beat AND per-step supervision.
    # NOTE: training on this is monitor DISTILLATION, not scheming detection.
    would_flag_now: bool | None = None
    cumulative_confidence: float | None = None


@dataclass(frozen=True)
class Trajectory:
    """One agent episode. The unit a trajectory-level label attaches to."""

    uid: str
    steps: tuple[Step, ...]
    label: int                      # 1 = scheming/misaligned, 0 = benign
    group_id: str                   # for group-aware CV; NEVER split a group
    source: str                     # corpus id, for provenance in results.json
    # --- oracle timing (SHADE only; None elsewhere) ---
    ideal_flagging_step: int | None = None   # -1 in the raw data for benign; None here
    point_of_no_return_step: int | None = None

    @property
    def n_steps(self) -> int:
        return len(self.steps)

    @property
    def available_lead(self) -> int | None:
        """point_of_no_return - ideal_flag. The headroom an ideal monitor would have.

        None when either oracle field is absent. This is the quantity the brief's
        "3.7 steps of advance warning" headline refers to -- and it is measurable here
        ONLY because the SHADE monitor-labels corpus ships both fields.
        """
        if self.ideal_flagging_step is None or self.point_of_no_return_step is None:
            return None
        return self.point_of_no_return_step - self.ideal_flagging_step


@dataclass
class Corpus:
    """A loaded corpus plus the provenance that makes its numbers auditable.

    ``requested`` vs ``achieved`` are BOTH recorded. Writing the requested value into
    results.json while the achieved value silently fell short is the exact defect the
    2026-08 audit found in biencoder_guard -- do not repeat it.
    """

    name: str
    trajectories: list[Trajectory]
    requested_n_per_class: int
    pool_fingerprint: str           # sha256 over the sorted uids actually sampled
    licence: str                    # "unstated" is a legitimate, and important, value
    # PROVENANCE IS TWO DIFFERENT THINGS AND CONFLATING THEM MISLEADS IN BOTH
    # DIRECTIONS. A single `label_provenance` field sitting on Corpus reads as if
    # it describes the labels the AUC ladder is scored against. On the
    # ControlArena pairs it does not:
    #
    #   trajectory label (pos/neg)  <- the dataset's own `ground_truth` 0/1 field
    #                                  (corpora/__init__.py), which is JUDGE-FREE
    #   per-step labels             <- `ideal_flagging_step`,
    #                                  `point_of_no_return_step`, which on SHADE /
    #                                  AgentDojo are Gemini-3.1-Pro judge output
    #
    # Read the old single field literally and you would wrongly discredit the
    # whole main ladder (F1/F3 are scored against ground_truth and are fine), and
    # simultaneously over-trust lead time (F5 is measured against a judge ORACLE,
    # never against truth). Both halves are now named separately.
    label_provenance: str           # TRAJECTORY labels: what pos/neg comes from
    step_label_provenance: str = "" # PER-STEP labels: oracle/PoNR timing source

    @property
    def achieved_n_pos(self) -> int:
        return sum(1 for t in self.trajectories if t.label == 1)

    @property
    def achieved_n_neg(self) -> int:
        return sum(1 for t in self.trajectories if t.label == 0)

    @property
    def n_distinct_groups(self) -> int:
        """Reported SEPARATELY from n, always.

        A corpus can inflate n without inflating information (SafeMTData_1K carries
        several actors per query_id). Conflating the two is the COUGHVID mistake.
        """
        return len({t.group_id for t in self.trajectories})

    def step_count_summary(self) -> dict:
        c = [t.n_steps for t in self.trajectories]
        if not c:
            return {"n": 0}
        a = np.asarray(c)
        return {
            "n": int(a.size), "min": int(a.min()), "median": float(np.median(a)),
            "mean": float(a.mean()), "max": int(a.max()),
        }

    def shortfall(self) -> dict:
        """Requested vs achieved, per class. Callers MUST warn loudly when it fires."""
        return {
            "requested_per_class": self.requested_n_per_class,
            "achieved_pos": self.achieved_n_pos,
            "achieved_neg": self.achieved_n_neg,
            "n_distinct_groups": self.n_distinct_groups,
            "shortfall": (self.achieved_n_pos < self.requested_n_per_class
                          or self.achieved_n_neg < self.requested_n_per_class),
            "clears_rule_1": (self.achieved_n_pos >= 500 and self.achieved_n_neg >= 500),
        }


@dataclass
class AggregatorResult:
    """What every aggregator returns. Uniform so the ladder is directly comparable."""

    method: str
    auc: float
    auc_ci: tuple[float, float]
    scores: np.ndarray = field(repr=False)          # [n_trajectories]
    latency_us_per_step: float | None = None
    notes: str = ""


@dataclass
class LeadTimeResult:
    """Early detection, reported as a DISTRIBUTION -- never a single mean.

    Measured: the oracle flag lands anywhere from 5.5% to 94% through a SHADE
    trajectory. A point estimate of "N steps of advance warning" would misrepresent
    that spread, so percentiles are required, not optional.
    """

    method: str
    n_positives_evaluated: int
    n_detected: int                                  # flagged at or before PONR
    lead_steps: np.ndarray = field(repr=False)       # per detected positive
    lead_p10: float = 0.0
    lead_median: float = 0.0
    lead_p90: float = 0.0
    false_alarm_rate: float = 0.0                    # on benign trajectories
    oracle_note: str = "lead measured against a judge oracle, NOT ground truth"


# --- interfaces --------------------------------------------------------------
@runtime_checkable
class Embedder(Protocol):
    """Turns step text into vectors. Default is EmbeddingGemma-300m (section 17 mandate).

    The weights ARE on disk -- CLAUDE.md section 18.5's "gated, no token" note is stale
    for the model, though several DATASETS remain genuinely gated.
    """

    name: str
    dim: int

    def encode(self, texts: Sequence[str]) -> np.ndarray:
        """-> float32 [len(texts), dim]. Deterministic for a fixed input."""
        ...


@runtime_checkable
class Aggregator(Protocol):
    """Collapses [n_steps, dim] -> one trajectory score. The thing under test.

    Implementations: mean_pool (the claim's target), max_pool, deviation_weighted,
    last_step (the control -- without it "trajectory detection" is indistinguishable
    from "the final step is just harmful"), gru, esn_cusum, query_token.
    """

    name: str
    is_causal: bool         # True iff score(prefix) never depends on future steps

    def fit(self, trajectories: Sequence[np.ndarray], labels: Sequence[int]) -> None: ...

    def score(self, trajectory: np.ndarray) -> float:
        """-> one score for the whole trajectory. Higher = more likely misaligned."""
        ...


@runtime_checkable
class StreamingAggregator(Aggregator, Protocol):
    """A causal monitor with BOUNDED state, updated one step at a time.

    ``is_causal`` MUST be True. This is what separates a genuine streaming monitor from
    an offline aggregator run over a prefix: state size must not grow with the horizon,
    and ``score_prefix`` must never look ahead.
    """

    def reset(self) -> None: ...

    def update(self, step_vec: np.ndarray) -> float:
        """Ingest ONE step, return the running score. O(1) in trajectory length."""
        ...

    def state_bytes(self) -> int:
        """Current state footprint. Must be O(1) in the number of steps seen."""
        ...


@runtime_checkable
class CorpusLoader(Protocol):
    """Loads one benchmark into the shared Corpus shape.

    MUST record licence honestly -- "unstated" for the community SHADE / AgentDojo
    re-dumps, which declare none -- and MUST record label_provenance.
    """

    name: str
    hf_id: str

    def load(self, n_per_class: int, seed: int) -> Corpus: ...


