"""taxonomy.py -- the deterministic THREE-LEVEL, 996-CATEGORY policy taxonomy for
EXP-H (the Opir taxonomy test).

------------------------------------------------------------------------------
WHY THIS FILE EXISTS, AND HOW IT DIFFERS FROM distractors.py
------------------------------------------------------------------------------
Opir ("Scaling Zero-Shot Information Extraction", Stepanov & Smechov,
arXiv:2605.29659) trains against "a three-level taxonomy containing 996 categories
across 16 top-level labels, 126 mid-level labels, and 854 leaf labels". This module
BUILDS THAT SHAPE on top of the lesson's 16 real toxic-chat/BeaverTails policies and
lets EXP-H score against it.

EXP-G (`distractors.py`) already padded the bank to ~900 labels -- but with
deliberately UNRELATED competitors: a disjoint ARTIFACT x DEFECT grid from
content-operations moderation, harm-stem blocklisted, Jaccard <= 0.20 against every
real description AND paraphrase. The 884 competitors there are STRANGERS. The result
(mean rank of the true policy 4.46 -> 62.55 frozen, 3.80 -> 113.01 trained) therefore
answers a comparatively easy question: can the guard keep the true policy near the
top when ~900 obviously-off-topic policies are added?

EXP-H asks the HARD version, and this is the entire point of the file:

    every one of the ~980 competitors is a SIBLING OR A DESCENDANT of a real
    policy -- a plausible near-miss, generated by NARROWING a real policy rather
    than by moving to a disjoint domain.

So where distractors.py works to MINIMISE semantic overlap with the real taxonomy
(four guards, one of which RAISES if the pool is exhausted), this file works to
MAXIMISE it in a controlled, auditable way: each mid-level label is a narrowing of
ITS top-level parent, each leaf a narrowing of ITS mid. The lexical-overlap number
that distractors.py treats as a FAILURE condition is here a DESIGN TARGET, and it is
reported (`lexical` in the audit) as evidence that the construction did what it
claims -- never as a filter.

------------------------------------------------------------------------------
THE ERROR-TAXONOMY POINT (why the breakdown matters more than the rank)
------------------------------------------------------------------------------
When a competitor outranks the true policy here, the violation is NOT homogeneous:

  * DESCENDANT  -- e.g. `Violence / threats of assault against a named individual`
                   outranking `Violence`. A router that sends the text to the
                   descendant has routed it to a MORE SPECIFIC, still-correct rule.
                   Arguably not an error at all; at worst an over-specification.
  * SIBLING     -- another TOP-LEVEL policy outranking the true one (the truth's
                   siblings under the virtual root). This is a genuine mis-route
                   and is exactly what EXP-A/EXP-G's K=16 condition already measures.
  * OTHER-BRANCH-- a mid/leaf under a DIFFERENT top-level policy (a "cousin"). Also a
                   genuine mis-route, and the closest analogue of EXP-G's unrelated
                   distractor stealing rank.

Reporting a single "steal rate" would silently price a descendant win as if it were
a cousin win. The runner therefore reports the breakdown, plus a DESCENDANT-CORRECTED
rank (the true policy's rank after removing its own descendants from the bank), and
an ENRICHMENT figure: the observed descendant share of violations divided by the
share a RANDOM violator would produce. Enrichment ~1 means the hierarchy is invisible
to the encoder; enrichment >> 1 means violations concentrate exactly where the
taxonomy says they should.

------------------------------------------------------------------------------
DETERMINISM, COUNTS, AND THE FINGERPRINT
------------------------------------------------------------------------------
Construction is a fixed nested loop over handwritten phrase tables -- no set
iteration, no dict-order dependence, NO randomness in the default path -- so the same
inputs always yield the same 980 nodes in the same order. `seed` is accepted and
recorded, and it is USED only when a caller asks for FEWER leaves than the grid
provides (a seeded, reproducible subsample); the default 854 uses the full grid, so
the default bank is seed-independent and we say so rather than implying a randomness
that is not there.

Counts are split by the exact Bresenham/largest-remainder rule
`n_i = floor((i+1)*T/N) - floor(i*T/N)`, so mids-per-parent is 7 or 8 (never 0 or 20)
and leaves-per-mid is 6 or 7, and the totals are EXACTLY 126 and 854 by arithmetic.
`build_taxonomy` ASSERTS the totals; it never returns a short bank, because a short
bank would quietly turn "K=996" into a smaller, easier K.

The bank is fingerprinted (sha256 over the ordered description list, 12 hex) and the
runner stores the fingerprint beside the cached embedding matrix, rejecting any cache
whose fingerprint disagrees. STAMP YOUR INPUTS.

ASCII-only stdout (Windows cp1252).
"""
