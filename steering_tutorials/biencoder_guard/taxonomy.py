# Phrasing templates. Index 0 is the DESCRIPTION; 1..4 are the PARAPHRASES, mirroring
# the real taxonomy's 1 + C.POLICY_PARAPHRASES layout so `encoders.build_policy_bank`
# consumes a taxonomy node unchanged. Two of the four name the PARENT explicitly --
# that is not a leak, it is how a hierarchical label reads ("Violence > threats ..."),
# and the lexical audit reports the overlap it produces instead of hiding it.
_PARAPHRASE_TEMPLATES = [
    "A narrower {parent} violation: {m}.",
    "Requests or material centred on {m}.",
    "Moderation subcategory of {parent}: {m}.",
    "Text whose core subject is {m}.",
]

