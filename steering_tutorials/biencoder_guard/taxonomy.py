_WORD_RE = re.compile(r"[a-z][a-z'-]*")


def _content_words(s: str) -> set:
    """Lowercase content-word set (function words + moderation boilerplate removed)."""
    return {w for w in _WORD_RE.findall(str(s).lower()) if w not in _STOPWORDS}


def _jaccard(a: set, b: set) -> float:
    if not a or not b:
        return 0.0
    return len(a & b) / float(len(a | b))


def _split_counts(total: int, n_bins: int) -> list:
    """Largest-remainder split: bin i gets floor((i+1)T/N) - floor(iT/N).

    Sums to EXACTLY `total` by construction, and spreads the remainder evenly so no
    parent is starved. Used for mids-per-parent (126 over 16 -> 7 or 8) and
    leaves-per-mid (854 over 126 -> 6 or 7).
    """
    if n_bins <= 0:
        raise ValueError("n_bins must be positive")
    out = [((i + 1) * total) // n_bins - (i * total) // n_bins for i in range(n_bins)]
    assert sum(out) == total, "largest-remainder split lost %d" % (total - sum(out))
    return out


def _short(phrase: str, n: int = 5) -> str:
    return " ".join(str(phrase).split()[:n])


def _node(node_id, name, phrase, parent_id, parent_name, top_index, level, frame):
    """One taxonomy node in the same dict shape the real policies use."""
    desc = frame.format(m=phrase)
    paras = [t.format(parent=parent_name, m=phrase) for t in _PARAPHRASE_TEMPLATES]
    return {
        "id": node_id,
        "name": name,
        "description": desc,
        "paraphrases": paras,
        "group": level,                 # "mid" | "leaf"
        "level": level,
        "parent_id": parent_id,
        "top_index": int(top_index),
        "phrase": phrase,
    }


def build_taxonomy(policies, n_mid: int = None, n_leaf: int = None,
                   seed: int = None, verbose: bool = True) -> dict:
    """Build the Opir-shaped taxonomy BELOW `policies` (the 16 top-level labels).

    Returns {"nodes": [...], "audit": {...}}. `nodes` is the 126 mids followed by the
    854 leaves, in a fixed order, each a Policy dict with the real taxonomy's keys
    plus {level, parent_id, top_index, phrase}. The caller stacks
    [16 real | 126 mid | 854 leaf] -> a 996-column bank.

    RAISES on any count mismatch or on a parent with no phrase table -- never returns
    a short or partial taxonomy.
    """
    n_mid = C.OPIR_N_MID if n_mid is None else int(n_mid)
    n_leaf = C.OPIR_N_LEAF if n_leaf is None else int(n_leaf)
    seed = C.OPIR_SEED if seed is None else int(seed)

    n_top = len(policies)
    for pol in policies:
        if pol["id"] not in _FRAME or pol["id"] not in _MIDS:
            raise KeyError("no taxonomy phrase table for top-level policy %r "
                           "-- add one rather than skipping the parent" % pol["id"])

    # --- mids: 7 or 8 per parent, exactly n_mid in total --------------------
    per_parent = _split_counts(n_mid, n_top)
    mids = []
    for ti, pol in enumerate(policies):
        avail = _MIDS[pol["id"]]
        want = per_parent[ti]
        if want > len(avail):
            raise ValueError("parent %s needs %d mid phrases, table has %d"
                             % (pol["id"], want, len(avail)))
        frame = _FRAME[pol["id"]]
        for k in range(want):
            phrase = avail[k]
            mids.append(_node(
                node_id="mid_%03d" % len(mids),
                name="%s / %s" % (pol["name"], _short(phrase)),
                phrase=phrase, parent_id=pol["id"], parent_name=pol["name"],
                top_index=ti, level="mid", frame=frame))
    assert len(mids) == n_mid, "built %d mids, wanted %d" % (len(mids), n_mid)

    # --- leaves: 6 or 7 per mid, exactly n_leaf in total --------------------
    per_mid = _split_counts(n_leaf, n_mid)
    max_facets = max(per_mid) if per_mid else 0
    if max_facets > len(_LEAF_FACETS):
        raise ValueError("need %d leaf facets, table has %d -- widen _LEAF_FACETS"
                         % (max_facets, len(_LEAF_FACETS)))
    leaves = []
    for mi, mid in enumerate(mids):
        parent_pol = policies[mid["top_index"]]
        frame = _FRAME[parent_pol["id"]]
        for k in range(per_mid[mi]):
            facet = _LEAF_FACETS[k]
            phrase = "%s, %s" % (mid["phrase"], facet)
            leaves.append(_node(
                node_id="leaf_%03d" % len(leaves),
                name="%s / %s" % (mid["name"], _short(facet, 4)),
                phrase=phrase, parent_id=mid["id"], parent_name=parent_pol["name"],
                top_index=mid["top_index"], level="leaf", frame=frame))
    assert len(leaves) == n_leaf, "built %d leaves, wanted %d" % (len(leaves), n_leaf)

    nodes = mids + leaves
    total = n_top + len(nodes)
    if total != C.OPIR_TOTAL:
        raise ValueError("taxonomy totals %d, expected %d (%d top + %d mid + %d leaf)"
                         % (total, C.OPIR_TOTAL, n_top, n_mid, n_leaf))

    descs = [n["description"] for n in nodes]
    if len(set(descs)) != len(descs):
        raise ValueError("duplicate node descriptions -- the grid is not injective")

    audit = _audit(policies, mids, leaves, seed)
    if verbose:
        lx = audit["lexical"]
        print("[taxo] %d top + %d mid + %d leaf = %d categories  fp=%s  "
              "mids/parent %d-%d  leaves/mid %d-%d"
              % (n_top, len(mids), len(leaves), total, audit["fingerprint"],
                 min(per_parent), max(per_parent), min(per_mid), max(per_mid)))
        print("[taxo] lexical adjacency (DESIGN TARGET, never a filter): mean Jaccard to "
              "OWN parent %.3f vs %.3f to the nearest OTHER parent (ratio %.2fx)"
              % (lx["mean_jaccard_own_parent"], lx["mean_jaccard_best_other_parent"],
                 lx["own_over_other_ratio"]))
    return {"nodes": nodes, "audit": audit}


def _audit(policies, mids, leaves, seed) -> dict:
    """Provenance + the LEXICAL ADJACENCY report (the inverse of distractors.py's G3).

    distractors.py DROPS a candidate whose Jaccard to a real phrasing exceeds 0.20.
    Here high overlap with the OWN parent is the point, so we do not filter -- we
    measure, and we measure it RELATIVELY: a node must look more like its own parent
    than like the closest other parent, otherwise "sibling/descendant" would be a
    label we assert rather than a property we built.
    """
    def phrasings(pol):
        return [str(pol.get("description", ""))] + [str(p) for p in pol.get("paraphrases", [])]

    parent_sets = [[_content_words(s) for s in phrasings(p)] for p in policies]

    own, best_other = [], []
    for node in mids + leaves:
        ws = _content_words(node["description"])
        ti = node["top_index"]
        own.append(max(_jaccard(ws, rs) for rs in parent_sets[ti]))
        others = [max(_jaccard(ws, rs) for rs in parent_sets[t])
                  for t in range(len(policies)) if t != ti]
        best_other.append(max(others) if others else 0.0)
    own = np.asarray(own, dtype=float)
    best_other = np.asarray(best_other, dtype=float)

    return {
        "seed": int(seed),
        "seed_used_for_subsampling": False,   # default path uses the full grid
        "n_top": int(len(policies)),
        "n_mid": int(len(mids)),
        "n_leaf": int(len(leaves)),
        "n_total": int(len(policies) + len(mids) + len(leaves)),
        "fingerprint": fingerprint(mids + leaves),
        "lexical": {
            "mean_jaccard_own_parent": float(own.mean()),
            "mean_jaccard_best_other_parent": float(best_other.mean()),
            "own_over_other_ratio": float(own.mean() / max(best_other.mean(), 1e-9)),
            "frac_closer_to_own_parent": float((own > best_other).mean()),
            "min_jaccard_own_parent": float(own.min()),
            "exp_g_gate_for_reference": float(C.DISTRACTOR_MAX_JACCARD),
            "frac_above_exp_g_gate": float((own > C.DISTRACTOR_MAX_JACCARD).mean()),
        },
        "examples": [n["description"] for n in (mids[:1] + leaves[:2])],
    }


def fingerprint(nodes) -> str:
    """sha256 over the ordered description list (12 hex). STAMP YOUR INPUTS."""
    h = hashlib.sha256()
    for n in nodes:
        h.update(str(n["description"]).encode("utf-8"))
        h.update(b"\x00")
    return h.hexdigest()[:12]


def relation_arrays(policies, nodes):
    """Column-aligned metadata for the assembled [16 real | nodes] bank.

    Returns (owner, level) as int arrays of length n_top + len(nodes):
      owner[c] = the TOP-LEVEL policy index column c belongs to (a top-level column
                 owns itself), so `owner[c] == j` <=> column c is j or a descendant of j.
      level[c] = 0 top, 1 mid, 2 leaf.
    These two arrays are the whole error taxonomy: given a true column j,
      level[c]==0 and c!=j          -> SIBLING (another top-level policy)
      owner[c]==j and level[c]>0    -> DESCENDANT of the truth
      owner[c]!=j and level[c]>0    -> OTHER-BRANCH (a cousin: mid/leaf of another parent)
    """
    n_top = len(policies)
    code = {"mid": 1, "leaf": 2}
    owner = np.array(list(range(n_top)) + [int(n["top_index"]) for n in nodes],
                     dtype=np.int32)
    level = np.array([0] * n_top + [code[n["level"]] for n in nodes], dtype=np.int32)
    return owner, level


def proximity_audit(node_bank: np.ndarray, real_bank: np.ndarray, owner_nodes) -> dict:
    """Report-only: how close does each node sit to its OWN parent vs the best other?

    The embedding-space twin of the lexical audit, and REPORT-ONLY for the same reason
    distractors.py's G4 is: selecting nodes with the encoder under test would rig the
    experiment. Here it would rig it in the easy direction (drop the confusable
    children), which is exactly the confusion EXP-H exists to measure.
    """
    D = np.asarray(node_bank, dtype=np.float32)
    R = np.asarray(real_bank, dtype=np.float32)
    if D.size == 0 or R.size == 0:
        return {"error": "empty bank"}
    D = D / np.maximum(np.linalg.norm(D, axis=1, keepdims=True), 1e-12)
    R = R / np.maximum(np.linalg.norm(R, axis=1, keepdims=True), 1e-12)
    Cm = D @ R.T                                   # [n_nodes, n_top]
    own = Cm[np.arange(Cm.shape[0]), np.asarray(owner_nodes, dtype=int)]
    masked = Cm.copy()
    masked[np.arange(Cm.shape[0]), np.asarray(owner_nodes, dtype=int)] = -np.inf
    best_other = masked.max(axis=1)
    return {
        "mean_cos_to_own_parent": float(own.mean()),
        "mean_cos_to_best_other_parent": float(best_other.mean()),
        "frac_closer_to_own_parent": float((own > best_other).mean()),
        "mean_max_cos_to_real": float(Cm.max(axis=1).mean()),
        "p95_max_cos_to_real": float(np.percentile(Cm.max(axis=1), 95)),
        "max_max_cos_to_real": float(Cm.max()),
        "n_above_0.90": int((Cm.max(axis=1) >= 0.90).sum()),
        "n_above_0.95": int((Cm.max(axis=1) >= 0.95).sum()),
    }


# ---------------------------------------------------------------------------
# CPU self-test: no model, no data download beyond the taxonomy definition.
# ---------------------------------------------------------------------------
def _self_test():
    from . import data

    # The self-test asserts Opir's EXACT 16/126/854 shape, so it runs on the 16 base
    # policies regardless of whether the live corpus pools Aegis' extra columns. The
    # runner's `_opir_fit_shape` handles the wider case at run time and records the
    # deviation; this test's job is to prove the paper's shape is buildable at all.
    policies = [p for p in data.build_taxonomy()
                if p["id"] in data.policy_order(extra_columns=False)]
    assert len(policies) == 16, "base taxonomy is %d wide, expected 16" % len(policies)
    built = build_taxonomy(policies, n_mid=126, n_leaf=854)
    nodes = built["nodes"]
    a = built["audit"]

    # shape: exactly Opir's 16 / 126 / 854 / 996.
    assert a["n_top"] == 16 and a["n_mid"] == 126 and a["n_leaf"] == 854
    assert a["n_total"] == 996 == C.OPIR_TOTAL

    # determinism: same inputs -> identical bank.
    again = build_taxonomy(policies, n_mid=126, n_leaf=854, verbose=False)["nodes"]
    assert fingerprint(nodes) == fingerprint(again), "generator not deterministic"

    # structure: every mid hangs off a real policy; every leaf off a mid with the
    # SAME top-level ancestor (a leaf that drifted parents would silently corrupt the
    # descendant/sibling breakdown, which is the experiment's whole output).
    by_id = {n["id"]: n for n in nodes}
    pol_ids = {p["id"] for p in policies}
    n_mid = a["n_mid"]
    for n in nodes[:n_mid]:
        assert n["level"] == "mid" and n["parent_id"] in pol_ids
        assert policies[n["top_index"]]["id"] == n["parent_id"]
    for n in nodes[n_mid:]:
        assert n["level"] == "leaf"
        parent = by_id[n["parent_id"]]
        assert parent["level"] == "mid"
        assert parent["top_index"] == n["top_index"], "leaf drifted from its mid's parent"

    # every parent is represented, and no parent is starved.
    counts = np.bincount([n["top_index"] for n in nodes[:n_mid]], minlength=len(policies))
    assert counts.min() >= 7 and counts.max() <= 8, "mids per parent out of range: %s" % counts

    # prototypes: build_policy_bank averages description + POLICY_PARAPHRASES-1
    # paraphrases, so every node must carry enough phrasings.
    for n in nodes:
        assert len(n["paraphrases"]) >= C.POLICY_PARAPHRASES - 1

    # relation arrays agree with the node metadata.
    owner, level = relation_arrays(policies, nodes)
    assert len(owner) == 996 and owner[:16].tolist() == list(range(16))
    assert (level[:16] == 0).all() and (level[16:16 + n_mid] == 1).all()
    assert (level[16 + n_mid:] == 2).all()

    # THE DEFINING CONTRAST WITH EXP-G, asserted rather than asserted-in-prose.
    # distractors.py guarantees Jaccard <= 0.20 to EVERY real phrasing. This taxonomy
    # must do the OPPOSITE: sit close to its own parent, and closer to its own parent
    # than to any other. If this ever failed, "related competitors" would be a claim
    # about intent rather than a property of the bank.
    lx = a["lexical"]
    assert lx["mean_jaccard_own_parent"] > C.DISTRACTOR_MAX_JACCARD, (
        "taxonomy nodes are NOT lexically adjacent to their parents (mean %.3f <= %.2f) "
        "-- EXP-H would then be a second unrelated-distractor test, not a sibling test"
        % (lx["mean_jaccard_own_parent"], C.DISTRACTOR_MAX_JACCARD))
    assert lx["frac_closer_to_own_parent"] > 0.90, (
        "only %.1f%% of nodes are lexically closest to their OWN parent"
        % (100 * lx["frac_closer_to_own_parent"]))

    print("taxonomy.py self-test OK: %d nodes below %d real policies (996 total), "
          "fp=%s, mean Jaccard to own parent %.3f vs %.3f other (%.1f%% closer to own); "
          "EXP-G's unrelated gate was <= %.2f"
          % (len(nodes), len(policies), a["fingerprint"],
             lx["mean_jaccard_own_parent"], lx["mean_jaccard_best_other_parent"],
             100 * lx["frac_closer_to_own_parent"], C.DISTRACTOR_MAX_JACCARD))


if __name__ == "__main__":
    _self_test()
